import { Shuffle } from 'lucide-react'
import * as React from 'react'
import { toast } from 'sonner'

import { ArenaPanel } from '@/components/arena/arena-ui'
import { Button } from '@/components/ui/button'
import { computeRoundRobinStandings } from '@/domain/standings'
import { errorMessage } from '@/features/auth/api'
import { cn } from '@/lib/cn'

import { saveTournamentDraw } from './api'
import { BracketView } from './bracket-view'
import { entryName, matchSideLabel, type EntryLookups } from './display'
import {
  DRAW_ORDER_LABELS,
  DRAW_ORDER_OPTIONS,
  drawPayloadFor,
  orderedEntryIds,
  type DrawOrder,
} from './draw'
import { ResultFormDialog, type ResultMode } from './result-form-dialog'
import { RoundRobinView } from './round-robin-view'
import { buildStandingsMatches, groupGamesByMatch } from './results'
import { StandingsTable } from './standings-table'
import type {
  MatchGameRecord,
  MatchRecord,
  TournamentEntryRecord,
  TournamentEventRecord,
  TournamentRecord,
} from './types'

interface ResultTarget {
  match: MatchRecord
  mode: ResultMode
}

export interface EventDrawProps {
  tournament: TournamentRecord
  event: TournamentEventRecord
  /** Entries for this event only. */
  entries: readonly TournamentEntryRecord[]
  /** Matches for this event only. */
  matches: readonly MatchRecord[]
  /** Set scores for this event only. */
  games: readonly MatchGameRecord[]
  entriesById: ReadonlyMap<string, TournamentEntryRecord>
  lookups: EntryLookups
  canManage: boolean
  /** True while the tournament is in progress. */
  canRecord: boolean
  /** Drop the panel header when the embedding stage already names the board. */
  headerless?: boolean
  onChanged: () => void
}

/**
 * One event's draw: generation controls, standings, bracket or schedule, and
 * result recording. Shared by the tournament page and the dedicated draw room
 * so both show exactly the same board.
 */
export function EventDraw({
  tournament,
  event,
  entries,
  matches,
  games,
  entriesById,
  lookups,
  canManage,
  canRecord,
  headerless = false,
  onChanged,
}: EventDrawProps) {
  const [drawOrder, setDrawOrder] = React.useState<DrawOrder>('seeded')
  const [generating, setGenerating] = React.useState(false)
  const [drawError, setDrawError] = React.useState<string | null>(null)
  const [result, setResult] = React.useState<ResultTarget | null>(null)

  const registeredEntries = React.useMemo(
    () => entries.filter((entry) => entry.status === 'registered'),
    [entries],
  )

  const drawExists = event.draw_generated_at !== null
  const completedMatches = matches.filter((match) => match.status === 'completed').length
  const mayRecord = canRecord && canManage

  const gamesByMatch = React.useMemo(() => groupGamesByMatch(games), [games])

  const matchesById = React.useMemo(
    () => new Map(matches.map((match) => [match.id, match])),
    [matches],
  )

  const standings = React.useMemo(() => {
    if (event.format !== 'round_robin') return null
    if (registeredEntries.length < 2 || completedMatches === 0) return null

    return computeRoundRobinStandings(
      registeredEntries.map((entry) => entry.id),
      buildStandingsMatches(matches, games),
    )
  }, [event.format, registeredEntries, completedMatches, matches, games])

  async function handleGenerateDraw() {
    setDrawError(null)
    setGenerating(true)

    try {
      const payload = drawPayloadFor(event.format, orderedEntryIds(registeredEntries), drawOrder)
      const outcome = await saveTournamentDraw(event.id, payload)
      toast.success(
        `Draw generated: ${outcome.match_count} match${outcome.match_count === 1 ? '' : 'es'}.`,
      )
      onChanged()
    } catch (generateError) {
      setDrawError(errorMessage(generateError))
    } finally {
      setGenerating(false)
    }
  }

  const resultHome = result
    ? matchSideLabel(result.match, 'home', matchesById, entriesById, lookups)
    : ''
  const resultAway = result
    ? matchSideLabel(result.match, 'away', matchesById, entriesById, lookups)
    : ''

  return (
    <ArenaPanel
      kicker="Draw room"
      title={drawExists ? 'Draw and results' : 'Draw'}
      description={
        drawExists
          ? 'Byes advance automatically. Results feed the bracket or the D9 standings.'
          : 'Generate the draw after the entries are final. This locks the entry list.'
      }
      headerless={headerless}
    >
      <div className="flex flex-col gap-3 p-3">
        {drawError ? (
          <p role="alert" className="text-sm font-medium text-danger">
            {drawError}
          </p>
        ) : null}

        {!drawExists ? (
          registeredEntries.length < 2 ? (
            <p className="text-sm text-text-muted">
              Add at least two registered entries before generating a draw.
            </p>
          ) : !canManage ? (
            <p className="text-sm text-text-muted">
              The draw is generated by tournament staff once entries close.
            </p>
          ) : (
            <div className="flex flex-col gap-3">
              <div className="flex flex-wrap items-center gap-2">
                <div className="flex flex-wrap gap-1.5" role="group" aria-label="Draw order">
                  {DRAW_ORDER_OPTIONS.map((option) => (
                    <button
                      key={option}
                      type="button"
                      aria-pressed={drawOrder === option}
                      onClick={() => setDrawOrder(option)}
                      className={cn(
                        'rounded-pill border px-3 py-1 text-[11px] uppercase tracking-[0.06em] transition-colors duration-fast',
                        'focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-accent-ring',
                        drawOrder === option
                          ? 'border-accent bg-accent-soft text-accent'
                          : 'border-border text-text-muted hover:border-border-strong hover:text-text',
                      )}
                    >
                      {DRAW_ORDER_LABELS[option]}
                    </button>
                  ))}
                </div>

                <Button onClick={() => void handleGenerateDraw()} loading={generating}>
                  <Shuffle aria-hidden="true" />
                  Generate draw
                </Button>
              </div>

              <p className="text-xs text-text-muted">
                Seed order places seeded entries first, then registration order. A random draw
                shuffles the same pool. Only fully paid or waived entries enter the draw; byes are
                not stored as matches.
              </p>
            </div>
          )
        ) : event.format === 'round_robin' ? (
          <div className="flex flex-col gap-5">
            {standings ? (
              <StandingsTable
                rows={standings.rows}
                unresolvedGroups={standings.unresolvedGroups}
                labelForEntry={(entryId) => entryName(entriesById.get(entryId), lookups)}
              />
            ) : (
              <p className="text-sm text-text-muted">
                Standings appear after the first completed result.
              </p>
            )}

            <div>
              <h3 className="mb-2 text-[11px] font-medium uppercase tracking-[0.1em] text-text-faint">
                Match schedule
              </h3>
              <RoundRobinView
                matches={matches}
                gamesByMatch={gamesByMatch}
                entriesById={entriesById}
                lookups={lookups}
                canRecord={mayRecord}
                onRecord={(match, mode) => setResult({ match, mode })}
              />
            </div>
          </div>
        ) : (
          <div className="flex flex-col gap-4">
            <BracketView
              matches={matches}
              gamesByMatch={gamesByMatch}
              entriesById={entriesById}
              lookups={lookups}
              canRecord={mayRecord}
              onRecord={(match, mode) => setResult({ match, mode })}
            />

            {!canRecord && tournament.status !== 'completed' ? (
              <p className="text-xs text-text-muted">Start the tournament to record results.</p>
            ) : null}
          </div>
        )}
      </div>

      {result ? (
        <ResultFormDialog
          key={`${result.match.id}-${result.mode}`}
          open
          match={result.match}
          homeName={resultHome}
          awayName={resultAway}
          existingGames={gamesByMatch.get(result.match.id) ?? []}
          mode={result.mode}
          onOpenChange={(open) => {
            if (!open) setResult(null)
          }}
          onSaved={() => {
            setResult(null)
            onChanged()
          }}
        />
      ) : null}
    </ArenaPanel>
  )
}
